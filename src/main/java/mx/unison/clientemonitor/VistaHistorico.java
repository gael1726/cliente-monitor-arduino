    /**
     * Inicializa la gráfica de JFreeChart
     */
    private void inicializarGrafica() {
        // Crear las series de datos
        serieX = new XYSeries("Eje X");
        serieY = new XYSeries("Eje Y");
        serieZ = new XYSeries("Eje Z");

        // Crear la colección de series
        XYSeriesCollection dataset = new XYSeriesCollection();
        dataset.addSeries(serieX);
        dataset.addSeries(serieY);
        dataset.addSeries(serieZ);

        // Crear la gráfica
        JFreeChart grafica = ChartFactory.createXYLineChart(
                "Datos Históricos del Sensor",
                "Registro",
                "Valor",
                dataset,
                PlotOrientation.VERTICAL,
                true, true, false
        );

        // Personalizar colores
        XYPlot plot = grafica.getXYPlot();
        plot.setBackgroundPaint(Color.WHITE);
        plot.setDomainGridlinePaint(Color.LIGHT_GRAY);
        plot.setRangeGridlinePaint(Color.LIGHT_GRAY);
        plot.getRenderer().setSeriesPaint(0, AZUL_UNISON);
        plot.getRenderer().setSeriesPaint(1, DORADO_UNISON);
        plot.getRenderer().setSeriesPaint(2, new Color(0, 150, 0));

        // Crear el panel de la gráfica
        chartPanel = new ChartPanel(grafica);

        // Agregar la gráfica al panelGrafica
        panelGrafica.setLayout(new BorderLayout());
        panelGrafica.add(chartPanel, BorderLayout.CENTER);
        panelGrafica.validate();
    }

    /**
     * Consulta los datos históricos del servidor Se ejecuta en un Thread para
     * no bloquear la interfaz
     */
    private void consultarDatos() {
        // Obtener los filtros de los campos de texto
        String fechaInicio = txtFechaInicio.getText().trim();
        String fechaFin = txtFechaFin.getText().trim();
        String horaInicio = txtHoraInicio.getText().trim();
        String horaFin = txtHoraFin.getText().trim();

        // Convertir strings vacíos a null
        if (fechaInicio.isEmpty()) {
            fechaInicio = null;
        }
        if (fechaFin.isEmpty()) {
            fechaFin = null;
        }
        if (horaInicio.isEmpty()) {
            horaInicio = null;
        }
        if (horaFin.isEmpty()) {
            horaFin = null;
        }

        // Deshabilitar botón mientras carga
        btnConsultar.setEnabled(false);
        lblEstado.setText("Estado: Cargando datos desde el servidor...");
        lblEstado.setForeground(Color.BLUE);

        // Crear un Thread para cargar datos en segundo plano
        final String fInicio = fechaInicio;
        final String fFin = fechaFin;
        final String hInicio = horaInicio;
        final String hFin = horaFin;

        Thread threadCarga = new Thread(() -> {
            try {
                System.out.println("→ Conectando al servidor...");

                // Conectar al servidor
                ConexionServidor conexion = new ConexionServidor();

                // Solicitar datos con filtros
                String datosEncriptados = conexion.solicitarDatosHistoricos(
                        fInicio, fFin, hInicio, hFin
                );

                // Cerrar conexión
                conexion.cerrarConexion();

                if (datosEncriptados == null) {
                    mostrarError("Error al obtener datos del servidor");
                    return;
                }

                if (datosEncriptados.equals("SIN_DATOS")) {
                    mostrarMensaje("No se encontraron datos con los filtros especificados");
                    return;
                }

                System.out.println("✓ Datos recibidos del servidor");

                // Desencriptar los datos
                String datosJSON = Encriptacion.desencriptar(datosEncriptados);
                System.out.println("✓ Datos desencriptados");
                System.out.println("JSON: " + datosJSON.substring(0, Math.min(100, datosJSON.length())) + "...");

                // Parsear y mostrar en la gráfica
                parsearYMostrarDatos(datosJSON);

            } catch (Exception e) {
                System.err.println("✗ Error: " + e.getMessage());
                e.printStackTrace();
                mostrarError("Error: " + e.getMessage());
            }
        });

        threadCarga.start();
    }

    /**
     * Parsea el JSON y muestra los datos en la gráfica
     */
    private void parsearYMostrarDatos(String datosJSON) {
        try {
            // Parsear el JSON
            JSONArray array = new JSONArray(datosJSON);

            if (array.length() == 0) {
                mostrarMensaje("No hay datos para mostrar");
                return;
            }

            System.out.println("→ Parseando " + array.length() + " registros...");

            // Limpiar series anteriores
            SwingUtilities.invokeLater(() -> {
                serieX.clear();
                serieY.clear();
                serieZ.clear();
            });

            // Agregar datos a las series
            for (int i = 0; i < array.length(); i++) {
                JSONObject obj = array.getJSONObject(i);

                int id = obj.getInt("id");
                int x = obj.getInt("x");
                int y = obj.getInt("y");
                int z = obj.getInt("z");

                // Usar el índice como eje X de la gráfica
                final int indice = i;
                final int valorX = x;
                final int valorY = y;
                final int valorZ = z;

                SwingUtilities.invokeLater(() -> {
                    serieX.add(indice, valorX);
                    serieY.add(indice, valorY);
                    serieZ.add(indice, valorZ);
                });
            }

            // Actualizar estado
            SwingUtilities.invokeLater(() -> {
                lblEstado.setText("Estado: " + array.length() + " registros cargados");
                lblEstado.setForeground(new Color(0, 150, 0));
                btnConsultar.setEnabled(true);
            });

            System.out.println("✓ Datos mostrados en la gráfica");

        } catch (Exception e) {
            System.err.println("✗ Error al parsear JSON: " + e.getMessage());
            e.printStackTrace();
            mostrarError("Error al procesar datos: " + e.getMessage());
        }
    }

    /**
     * Muestra un mensaje de error
     */
    private void mostrarError(String mensaje) {
        SwingUtilities.invokeLater(() -> {
            lblEstado.setText("Estado: " + mensaje);
            lblEstado.setForeground(Color.RED);
            btnConsultar.setEnabled(true);
            JOptionPane.showMessageDialog(this, mensaje, "Error", JOptionPane.ERROR_MESSAGE);
        });
    }

    /**
     * Muestra un mensaje informativo
     */
    private void mostrarMensaje(String mensaje) {
        SwingUtilities.invokeLater(() -> {
            lblEstado.setText("Estado: " + mensaje);
            lblEstado.setForeground(Color.ORANGE);
            btnConsultar.setEnabled(true);
            JOptionPane.showMessageDialog(this, mensaje, "Información", JOptionPane.INFORMATION_MESSAGE);
        });
    }

    /**
     * Limpia los filtros y la gráfica
     */
    private void limpiarFiltros() {
        txtFechaInicio.setText("");
        txtFechaFin.setText("");
        txtHoraInicio.setText("");
        txtHoraFin.setText("");

        serieX.clear();
        serieY.clear();
        serieZ.clear();

        lblEstado.setText("Estado: Filtros limpiados");
        lblEstado.setForeground(Color.GRAY);
    }

