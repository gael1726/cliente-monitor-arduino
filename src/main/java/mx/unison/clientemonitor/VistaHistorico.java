    private void btnVerRangoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVerRangoActionPerformed
        Thread thread = new Thread(() -> {
            try {
                ConexionServidor conexion = new ConexionServidor();
                String datosEncriptados = conexion.solicitarTodosDatos();
                conexion.cerrarConexion();

                if (datosEncriptados == null || datosEncriptados.equals("SIN_DATOS")) {
                    return;
                }

                String datosJSON = Encriptacion.desencriptar(datosEncriptados);
                JSONArray array = new JSONArray(datosJSON);

                if (array.length() > 0) {
                    JSONObject primero = array.getJSONObject(array.length() - 1);
                    JSONObject ultimo = array.getJSONObject(0);

                    String fechaPrimero = primero.getString("fecha");
                    String horaPrimero = primero.getString("hora");
                    String fechaUltimo = ultimo.getString("fecha");
                    String horaUltimo = ultimo.getString("hora");

                    SwingUtilities.invokeLater(() -> {
                        txtFechaInicio.setText(fechaPrimero);
                        txtHoraInicio.setText(horaPrimero);
                        txtFechaFin.setText(fechaUltimo);
                        txtHoraFin.setText(horaUltimo);

                        JOptionPane.showMessageDialog(this,
                                "Rango completo cargado:\n"
                                + "Desde: " + fechaPrimero + " " + horaPrimero + "\n"
                                + "Hasta: " + fechaUltimo + " " + horaUltimo,
                                "Rango Auto-Completado", JOptionPane.INFORMATION_MESSAGE);
                    });
                }

            } catch (Exception e) {
                e.printStackTrace();
            }
        });
        thread.start();

    }//GEN-LAST:event_btnVerRangoActionPerformed

